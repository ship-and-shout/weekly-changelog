import { changelogEntry } from "./changelog";
import { weekItems } from "./classify";
import { branchExists, commitDirect, openPr, readFile, readWeek, type Octokit, type Repo, type WriteResult } from "./github";
import { hasEntry, spliceEntry } from "./splice";
import type { Week } from "./week";

export type Mode = "pr" | "commit" | "none";

export interface RunInput {
  repo: Repo;
  isPrivate: boolean;
  base: string;
  week: Week;
  mode: Mode;
  path: string;
  skipEmpty: boolean;
}

export interface RunOutput {
  entry: string;
  empty: boolean;
  /** What happened, for the job summary/log. */
  note: string;
  write: WriteResult | null;
}

const ACTION_URL = "https://github.com/ship-and-shout/weekly-changelog";

/** PR-body footer. The changelog file never gets this. */
export function footer(r: Repo, isPrivate: boolean): string {
  const utm = "utm_source=changelog-action";
  const link = isPrivate
    ? `https://www.shipandshout.com/?${utm}`
    : `https://www.shipandshout.com/try/${encodeURIComponent(r.owner)}/${encodeURIComponent(r.repo)}?${utm}`;
  return `---\nGenerated by [Weekly Changelog](${ACTION_URL}).\nWant this week as a post for X / LinkedIn / Bluesky? → ${link}`;
}

export async function run(octokit: Octokit, i: RunInput): Promise<RunOutput> {
  const data = await readWeek(octokit, i.repo, i.base, i.week);
  const items = weekItems(data.commitMessages, data.prTitles);
  const entry = changelogEntry({ weekStart: i.week.start, items, releases: data.releases });
  const empty = items.length === 0 && data.releases.length === 0;
  const cappedNote = data.capped ? "\n\n_Very busy week: GitHub's lists were capped, so a few items may be missing._" : "";

  if (i.mode === "none") return { entry, empty, note: "mode: none, nothing written", write: null };
  if (empty && i.skipEmpty) return { entry, empty, note: `No user-facing changes in ${i.week.label}; skipped (skip-empty: true)`, write: null };

  const branch = `changelog/week-${i.week.start}`;
  if (i.mode === "pr" && (await branchExists(octokit, i.repo, branch))) {
    return { entry, empty, note: `Branch ${branch} already exists; skipped`, write: null };
  }
  const file = await readFile(octokit, i.repo, i.path, i.base);
  if (file && hasEntry(file.text, entry)) {
    return { entry, empty, note: `${i.path} already has ${i.week.label}; skipped`, write: null };
  }

  const content = spliceEntry(file?.text ?? null, entry);
  const message = `docs(changelog): week of ${i.week.label}`;
  const write =
    i.mode === "pr"
      ? await openPr(octokit, i.repo, {
          base: i.base,
          branch,
          path: i.path,
          content,
          fileSha: file?.sha,
          message,
          title: message,
          body: `Adds the week of ${i.week.label} to \`${i.path}\`, built from merged PRs, conventional commits and releases between ${i.week.start} and ${i.week.end} (UTC).\n\n${entry}${cappedNote}\n\n${footer(i.repo, i.isPrivate)}`,
        })
      : await commitDirect(octokit, i.repo, { base: i.base, path: i.path, content, fileSha: file?.sha, message });
  return { entry, empty, note: write.kind === "pr" ? `Opened ${write.url}` : `Committed ${write.url}`, write };
}
